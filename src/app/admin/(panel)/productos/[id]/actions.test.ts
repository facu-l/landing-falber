// @vitest-environment node
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { PRODUCT_DATA_ERRORS, PRODUCT_DATA_NOT_SAVED, PRODUCT_DATA_SAVE_ERROR } from "@/lib/admin/product-data";
import { PHOTO_ERRORS } from "@/lib/admin/product-photo";
import { PUBLISH_ERRORS } from "@/lib/admin/product-publish";

const mocks = vi.hoisted(() => ({
  requireAdminAction: vi.fn(),
  updateTag: vi.fn(),
  refresh: vi.fn(),
  // products: select(...).eq().maybeSingle() y update().eq().select()
  readProduct: vi.fn(),
  update: vi.fn(),
  // Cada .eq() / .is() del update, en orden.
  filter: vi.fn(),
  updateResult: vi.fn(),
  // storage.from("product-images")
  createSignedUploadUrl: vi.fn(),
  exists: vi.fn(),
  remove: vi.fn(),
  storageFrom: vi.fn(),
}));

vi.mock("server-only", () => ({}));
vi.mock("next/cache", () => ({ updateTag: mocks.updateTag, refresh: mocks.refresh }));
vi.mock("@/lib/admin/auth", () => ({ requireAdminAction: mocks.requireAdminAction }));

const { requestPhotoUpload, savePhoto, updateProductData, updateProductStatus } = await import("./actions");

const PRODUCT_ID = "11111111-1111-1111-1111-111111111111";
const NEW_PATH = "dior-sauvage-0123456789ab.webp";
const OLD_PATH = "dior-sauvage-aaaaaaaaaaaa.webp";

function supabase() {
  return {
    from: () => ({
      select: () => ({ eq: () => ({ maybeSingle: mocks.readProduct }) }),
      update: (values: unknown) => {
        mocks.update(values);
        const chain = {
          eq: (column: string, value: unknown) => (mocks.filter("eq", column, value), chain),
          is: (column: string, value: unknown) => (mocks.filter("is", column, value), chain),
          select: mocks.updateResult,
        };
        return chain;
      },
    }),
    storage: { from: mocks.storageFrom },
  };
}

beforeEach(() => {
  mocks.requireAdminAction.mockResolvedValue({ ok: true, supabase: supabase(), user: { id: "admin" } });
  mocks.readProduct.mockResolvedValue({ data: { slug: "dior-sauvage", image_path: OLD_PATH }, error: null });
  mocks.updateResult.mockResolvedValue({ data: [{ id: PRODUCT_ID }], error: null });
  mocks.storageFrom.mockReturnValue({
    createSignedUploadUrl: mocks.createSignedUploadUrl,
    exists: mocks.exists,
    remove: mocks.remove,
  });
  mocks.createSignedUploadUrl.mockImplementation(async (path: string) => ({
    data: { signedUrl: `http://storage/sign/${path}?token=t`, path, token: "t" },
    error: null,
  }));
  mocks.exists.mockResolvedValue({ data: true, error: null });
  mocks.remove.mockImplementation(async (paths: string[]) => ({ data: paths.map((name) => ({ name })), error: null }));
});

afterEach(() => {
  vi.clearAllMocks();
  vi.restoreAllMocks();
});

describe("requestPhotoUpload", () => {
  it("sin admin no firma nada (requireAdminAction corta con un redirect)", async () => {
    mocks.requireAdminAction.mockRejectedValue(new Error("NEXT_REDIRECT"));
    await expect(requestPhotoUpload(PRODUCT_ID, "image/webp")).rejects.toThrow("NEXT_REDIRECT");
    expect(mocks.createSignedUploadUrl).not.toHaveBeenCalled();
  });

  it("firma una ruta del slug del producto, armada en el servidor", async () => {
    const result = await requestPhotoUpload(PRODUCT_ID, "image/jpeg");

    expect(mocks.storageFrom).toHaveBeenCalledWith("product-images");
    const [path] = mocks.createSignedUploadUrl.mock.calls[0];
    expect(path).toMatch(/^dior-sauvage-[0-9a-f]{12}\.jpg$/);
    expect(result).toEqual({ ok: true, signedUrl: `http://storage/sign/${path}?token=t`, path });
  });

  it("un tipo que el bucket no acepta no se firma", async () => {
    await expect(requestPhotoUpload(PRODUCT_ID, "image/png")).resolves.toEqual({
      ok: false,
      message: PHOTO_ERRORS.unreadable,
    });
    expect(mocks.createSignedUploadUrl).not.toHaveBeenCalled();
  });

  it("un producto que no existe no se firma", async () => {
    mocks.readProduct.mockResolvedValue({ data: null, error: null });
    await expect(requestPhotoUpload(PRODUCT_ID, "image/webp")).resolves.toEqual({
      ok: false,
      message: PHOTO_ERRORS.notFound,
    });
  });

  // Generated by /ship test coverage audit.
  // Value: protects=a DB error reading the product returns the retryable upload message, logged without details, and signs nothing;
  // fails_when=the read error is ignored or treated as notFound ("ya no existe") or the raw error with details is logged;
  // why_new=only the not-found and sign-failure branches were tested; seam=none;
  // no_claim=real Supabase error shapes (supabase client mocked; unit only)
  it("si la base no responde al leer el producto, no firma y pide reintentar (sin loguear details)", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.readProduct.mockResolvedValue({ data: null, error: { code: "XX000", message: "fetch failed", details: "x" } });

    await expect(requestPhotoUpload(PRODUCT_ID, "image/webp")).resolves.toEqual({
      ok: false,
      message: PHOTO_ERRORS.upload,
    });
    expect(mocks.createSignedUploadUrl).not.toHaveBeenCalled();
    expect(log).toHaveBeenCalledWith("[admin] leer el producto para la foto falló", { code: "XX000", message: "fetch failed" });
  });

  it("si Storage no firma, avisa y lo loguea", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.createSignedUploadUrl.mockResolvedValue({ data: null, error: { message: "new row violates policy" } });

    await expect(requestPhotoUpload(PRODUCT_ID, "image/webp")).resolves.toEqual({
      ok: false,
      message: PHOTO_ERRORS.upload,
    });
    expect(log).toHaveBeenCalled();
  });
});

describe("savePhoto", () => {
  it("sin admin no escribe nada", async () => {
    mocks.requireAdminAction.mockRejectedValue(new Error("NEXT_REDIRECT"));
    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).rejects.toThrow("NEXT_REDIRECT");
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("guarda la ruta, borra la anterior, vence el caché de la tienda y refresca", async () => {
    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: true });

    expect(mocks.exists).toHaveBeenCalledWith(NEW_PATH);
    expect(mocks.update).toHaveBeenCalledWith({ image_path: NEW_PATH });
    expect(mocks.remove).toHaveBeenCalledWith([OLD_PATH]);
    expect(mocks.updateTag).toHaveBeenCalledWith("catalog");
    expect(mocks.refresh).toHaveBeenCalled();
  });

  it("guarda solo si la foto sigue siendo la que leyó (compare-and-set entre pestañas)", async () => {
    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: true });
    expect(mocks.filter.mock.calls).toEqual([
      ["eq", "id", PRODUCT_ID],
      ["eq", "image_path", OLD_PATH],
    ]);
  });

  it("sin foto anterior, el compare-and-set pide que siga sin foto", async () => {
    mocks.readProduct.mockResolvedValue({ data: { slug: "dior-sauvage", image_path: null }, error: null });
    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: true });
    expect(mocks.filter).toHaveBeenCalledWith("is", "image_path", null);
  });

  it("sin foto anterior no borra nada", async () => {
    mocks.readProduct.mockResolvedValue({ data: { slug: "dior-sauvage", image_path: null }, error: null });
    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: true });
    expect(mocks.remove).not.toHaveBeenCalled();
  });

  // Generated by /ship test coverage audit.
  // Value: protects=a DB error reading the product in savePhoto returns the retryable save message and touches neither bucket nor row;
  // fails_when=the read error falls through to notFound/invalidPath, or the action keeps going and writes or deletes;
  // why_new=savePhoto tests cover not-found paths and update failures, not the read error; seam=none;
  // no_claim=real Supabase error shapes (supabase client and storage mocked; unit only)
  it("si la base no responde al leer el producto, no toca el bucket ni la fila y pide reintentar", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.readProduct.mockResolvedValue({ data: null, error: { code: "XX000", message: "fetch failed", details: "x" } });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: false, message: PHOTO_ERRORS.save });
    expect(mocks.exists).not.toHaveBeenCalled();
    expect(mocks.update).not.toHaveBeenCalled();
    expect(mocks.remove).not.toHaveBeenCalled();
    expect(log).toHaveBeenCalledWith("[admin] leer el producto para la foto falló", { code: "XX000", message: "fetch failed" });
  });

  // Generated by /ship test coverage audit.
  // Value: protects=savePhoto on a deleted product says "ya no existe" and never checks, writes or deletes in the bucket;
  // fails_when=the !product guard is removed (crash on product.slug) or maps to another message;
  // why_new=only requestPhotoUpload tests the missing product; savePhoto's own guard had no test; seam=none;
  // no_claim=RLS hiding the row in a real DB (supabase client mocked; unit only)
  it("un producto que ya no existe no guarda nada y lo dice", async () => {
    mocks.readProduct.mockResolvedValue({ data: null, error: null });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: false, message: PHOTO_ERRORS.notFound });
    expect(mocks.exists).not.toHaveBeenCalled();
    expect(mocks.update).not.toHaveBeenCalled();
    expect(mocks.remove).not.toHaveBeenCalled();
  });

  it.each([
    ["con otra forma", "dior-sauvage.webp"],
    ["de otro producto", "creed-aventus-0123456789ab.webp"],
    ["de un slug que empieza igual", "dior-sauvage-edt-0123456789ab.webp"],
  ])("rechaza una ruta %s sin tocar la base ni el bucket (D6)", async (_case, path) => {
    // uploadAgain: reintentar con esta ruta no sirve; el campo vuelve a pedir una URL y sube.
    await expect(savePhoto(PRODUCT_ID, path)).resolves.toEqual({
      ok: false,
      message: PHOTO_ERRORS.invalidPath,
      uploadAgain: true,
    });
    expect(mocks.exists).not.toHaveBeenCalled();
    expect(mocks.update).not.toHaveBeenCalled();
    expect(mocks.remove).not.toHaveBeenCalled();
  });

  it("rechaza una ruta que no está en el bucket (subida cortada o inventada)", async () => {
    mocks.exists.mockResolvedValue({ data: false, error: { message: "Object not found" } });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({
      ok: false,
      message: PHOTO_ERRORS.invalidPath,
      uploadAgain: true,
    });
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("si Storage no responde al verificar (5xx, red), es un error de guardado: no explota ni toca la base", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    // storage-js solo devuelve data:false con 400/404; el resto lo lanza.
    mocks.exists.mockRejectedValue(new Error("Internal Server Error"));

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: false, message: PHOTO_ERRORS.save });
    expect(mocks.update).not.toHaveBeenCalled();
    expect(mocks.remove).not.toHaveBeenCalled();
    expect(log).toHaveBeenCalledWith("[admin] verificar la foto subida falló", "Internal Server Error");
  });

  it("si la base no guarda, borra la foto nueva y conserva la anterior", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.updateResult.mockResolvedValue({ data: null, error: { code: "XX000", message: "fetch failed", details: "x" } });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: false, message: PHOTO_ERRORS.save });
    expect(mocks.remove).toHaveBeenCalledWith([NEW_PATH]);
    expect(mocks.remove).not.toHaveBeenCalledWith([OLD_PATH]);
    expect(log).toHaveBeenCalledWith("[admin] guardar la foto del producto falló", { code: "XX000", message: "fetch failed" });
    expect(mocks.updateTag).not.toHaveBeenCalled();
  });

  it("si el update da error pero la foto nueva sí quedó guardada, no la borra: sigue como éxito", async () => {
    vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.updateResult.mockResolvedValue({ data: null, error: { code: "XX000", message: "fetch failed" } });
    // Primera lectura: la foto anterior. Después del error: la fila ya apunta a la nueva.
    mocks.readProduct
      .mockResolvedValueOnce({ data: { slug: "dior-sauvage", image_path: OLD_PATH }, error: null })
      .mockResolvedValueOnce({ data: { slug: "dior-sauvage", image_path: NEW_PATH }, error: null });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: true });
    expect(mocks.remove.mock.calls).toEqual([[[OLD_PATH]]]);
    expect(mocks.updateTag).toHaveBeenCalledWith("catalog");
  });

  it("si el update y la relectura fallan, no borra ninguna foto: la nueva pudo haber quedado guardada", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.updateResult.mockResolvedValue({ data: null, error: { code: "XX000", message: "fetch failed" } });
    mocks.readProduct
      .mockResolvedValueOnce({ data: { slug: "dior-sauvage", image_path: OLD_PATH }, error: null })
      .mockResolvedValueOnce({ data: null, error: { code: "XX000", message: "fetch failed" } });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: false, message: PHOTO_ERRORS.unconfirmed });
    expect(mocks.remove).not.toHaveBeenCalled();
    expect(log).toHaveBeenCalledWith("[admin] releer el producto tras el fallo falló", {
      code: "XX000",
      message: "fetch failed",
    });
    // Pudo haberse guardado: la tienda se vuelve a leer. La ficha no: con la base caída,
    // re-renderizarla lanzaría y el admin perdería el campo de la foto.
    expect(mocks.updateTag).toHaveBeenCalledWith("catalog");
    expect(mocks.refresh).not.toHaveBeenCalled();
  });

  // 0 filas: otra pestaña ganó el compare-and-set, o RLS no dejó escribir. En los dos casos
  // la foto nueva no quedó en ningún producto: se borra, y la publicada no se toca.
  it("si no tocó ninguna fila (compare-and-set perdido o RLS), borra solo su foto nueva", async () => {
    mocks.updateResult.mockResolvedValue({ data: [], error: null });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: false, message: PHOTO_ERRORS.save });
    expect(mocks.remove.mock.calls).toEqual([[[NEW_PATH]]]);
    expect(mocks.updateTag).not.toHaveBeenCalled();
    expect(mocks.refresh).not.toHaveBeenCalled();
  });

  it("si borrar la anterior falla, la foto nueva igual queda guardada (solo se loguea)", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.remove.mockResolvedValue({ data: null, error: { message: "timeout" } });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: true });
    expect(log).toHaveBeenCalledWith("[admin] borrar la foto anterior falló", "timeout");
    expect(mocks.updateTag).toHaveBeenCalledWith("catalog");
  });

  it("un borrado que no borra nada (RLS sin select, ver 0004) también se loguea", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.remove.mockResolvedValue({ data: [], error: null });

    await expect(savePhoto(PRODUCT_ID, NEW_PATH)).resolves.toEqual({ ok: true });
    expect(log).toHaveBeenCalledWith("[admin] borrar la foto anterior falló", "no se borró ningún objeto");
  });
});

describe("updateProductData", () => {
  const IDLE = { status: "idle" } as const;
  const VALUES = { brand: "Dior", name: "Sauvage EDT", gender: "male", description: "Fresco.", featured: "on" };

  function form(fields: Record<string, string>) {
    const data = new FormData();
    for (const [key, value] of Object.entries(fields)) data.set(key, value);
    return data;
  }

  it("sin admin no escribe nada", async () => {
    mocks.requireAdminAction.mockRejectedValue(new Error("NEXT_REDIRECT"));
    await expect(updateProductData(PRODUCT_ID, IDLE, form(VALUES))).rejects.toThrow("NEXT_REDIRECT");
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("guarda los datos sin tocar el slug, vence el caché de la tienda y refresca", async () => {
    await expect(updateProductData(PRODUCT_ID, IDLE, form({ ...VALUES, slug: "otro" }))).resolves.toEqual({
      status: "success",
      message: "Datos guardados.",
    });
    expect(mocks.update).toHaveBeenCalledWith({
      brand: "Dior",
      name: "Sauvage EDT",
      gender: "male",
      description: "Fresco.",
      is_featured: true,
    });
    expect(mocks.updateTag).toHaveBeenCalledWith("catalog");
    expect(mocks.refresh).toHaveBeenCalled();
  });

  it("datos inválidos no llegan a la base y vuelven con lo escrito", async () => {
    await expect(updateProductData(PRODUCT_ID, IDLE, form({ ...VALUES, gender: "otro" }))).resolves.toEqual({
      status: "error",
      fieldErrors: { gender: PRODUCT_DATA_ERRORS.gender },
      values: { ...VALUES, gender: "otro" },
    });
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("si no tocó ninguna fila, avisa y no vence el caché", async () => {
    mocks.updateResult.mockResolvedValue({ data: [], error: null });
    await expect(updateProductData(PRODUCT_ID, IDLE, form(VALUES))).resolves.toMatchObject({
      status: "error",
      message: PRODUCT_DATA_NOT_SAVED,
    });
    expect(mocks.updateTag).not.toHaveBeenCalled();
  });

  it("un error de la base se loguea sin details, con mensaje genérico y lo escrito", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.updateResult.mockResolvedValue({ data: null, error: { code: "XX000", message: "fetch failed", details: "fila" } });

    await expect(updateProductData(PRODUCT_ID, IDLE, form(VALUES))).resolves.toEqual({
      status: "error",
      message: PRODUCT_DATA_SAVE_ERROR,
      values: VALUES,
    });
    expect(log).toHaveBeenCalledWith("[admin] guardar los datos del producto falló", { code: "XX000", message: "fetch failed" });
  });
});

describe("acceso sin verificar (requireAdminAction no redirige: Auth o la base no responden)", () => {
  const ACCESS_FAILED = { ok: false, message: "No pudimos verificar tu acceso." } as const;

  function form(fields: Record<string, string>) {
    const data = new FormData();
    for (const [key, value] of Object.entries(fields)) data.set(key, value);
    return data;
  }

  beforeEach(() => mocks.requireAdminAction.mockResolvedValue(ACCESS_FAILED));

  it.each([
    ["requestPhotoUpload", () => requestPhotoUpload(PRODUCT_ID, "image/webp")],
    ["savePhoto", () => savePhoto(PRODUCT_ID, NEW_PATH)],
  ])("%s devuelve el mensaje y no toca la base ni el bucket", async (_name, run) => {
    await expect(run()).resolves.toEqual({ ok: false, message: ACCESS_FAILED.message });
    expect(mocks.readProduct).not.toHaveBeenCalled();
    expect(mocks.storageFrom).not.toHaveBeenCalled();
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("updateProductData vuelve al formulario con lo escrito, sin guardar", async () => {
    const values = { brand: "Dior", name: "Sauvage", gender: "", description: "" };
    await expect(updateProductData(PRODUCT_ID, { status: "idle" }, form(values))).resolves.toEqual({
      status: "error",
      message: ACCESS_FAILED.message,
      values,
    });
    expect(mocks.update).not.toHaveBeenCalled();
  });
});

describe("updateProductStatus", () => {
  const IDLE = { status: "idle" } as const;
  const status = (value: string) => {
    const data = new FormData();
    data.set("status", value);
    return data;
  };

  it("sin admin no escribe nada", async () => {
    mocks.requireAdminAction.mockRejectedValue(new Error("NEXT_REDIRECT"));
    await expect(updateProductStatus(PRODUCT_ID, IDLE, status("active"))).rejects.toThrow("NEXT_REDIRECT");
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("si no se pudo verificar el acceso, avisa sin escribir", async () => {
    mocks.requireAdminAction.mockResolvedValue({ ok: false, message: "Sin acceso" });
    expect(await updateProductStatus(PRODUCT_ID, IDLE, status("active"))).toEqual({ status: "error", message: "Sin acceso" });
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("publica, vence el caché de la tienda y refresca", async () => {
    expect(await updateProductStatus(PRODUCT_ID, IDLE, status("active"))).toEqual({
      status: "success",
      published: true,
      message: "Publicado.",
    });
    expect(mocks.update).toHaveBeenCalledWith({ status: "active" });
    expect(mocks.filter).toHaveBeenCalledWith("eq", "id", PRODUCT_ID);
    expect(mocks.updateTag).toHaveBeenCalledWith("catalog");
    expect(mocks.refresh).toHaveBeenCalled();
  });

  it("oculta y lo dice", async () => {
    expect(await updateProductStatus(PRODUCT_ID, IDLE, status("inactive"))).toEqual({
      status: "success",
      published: false,
      message: "Oculto. Ya no aparece en la tienda.",
    });
    expect(mocks.update).toHaveBeenCalledWith({ status: "inactive" });
  });

  it("un estado que no es publicar ni ocultar no escribe", async () => {
    expect(await updateProductStatus(PRODUCT_ID, IDLE, status("archived"))).toEqual({
      status: "error",
      message: PUBLISH_ERRORS.save,
    });
    expect(mocks.update).not.toHaveBeenCalled();
  });

  it("si la base dice que falta algo, lo nombra y no lo loguea (es nuestro)", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.updateResult.mockResolvedValue({ data: null, error: { message: "PRODUCT_NOT_PUBLISHABLE", details: "image" } });
    expect(await updateProductStatus(PRODUCT_ID, IDLE, status("active"))).toEqual({
      status: "error",
      message: PUBLISH_ERRORS.image,
    });
    expect(log).not.toHaveBeenCalled();
    expect(mocks.updateTag).not.toHaveBeenCalled();
  });

  it("otro error se loguea sin details y pide reintentar", async () => {
    const log = vi.spyOn(console, "error").mockImplementation(() => {});
    mocks.updateResult.mockResolvedValue({
      data: null,
      error: { code: "08006", message: "connection", details: "Failing row contains (...)" },
    });
    expect(await updateProductStatus(PRODUCT_ID, IDLE, status("active"))).toEqual({ status: "error", message: PUBLISH_ERRORS.save });
    expect(log).toHaveBeenCalledWith(expect.any(String), { code: "08006", message: "connection" });
  });

  it("0 filas (RLS o id inexistente) no se da por guardado", async () => {
    mocks.updateResult.mockResolvedValue({ data: [], error: null });
    expect(await updateProductStatus(PRODUCT_ID, IDLE, status("inactive"))).toEqual({
      status: "error",
      message: PUBLISH_ERRORS.notSaved,
    });
    expect(mocks.updateTag).not.toHaveBeenCalled();
  });
});
