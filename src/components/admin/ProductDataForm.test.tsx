import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { NEW_PRODUCT_ERRORS } from "@/lib/admin/product-list";
import { PRODUCT_DATA_SAVE_ERROR, type ProductDataState } from "@/lib/admin/product-data";

const mocks = vi.hoisted(() => ({ updateProductData: vi.fn() }));
vi.mock("@/app/admin/(panel)/productos/[id]/actions", () => ({ updateProductData: mocks.updateProductData }));

const { ProductDataForm } = await import("./ProductDataForm");

const product = {
  id: "p1",
  slug: "dior-sauvage-edt",
  brand: "Dior",
  name: "Sauvage EDT",
  gender: null,
  description: null,
  is_featured: true,
};

const field = <T extends HTMLElement = HTMLInputElement>(label: string) => screen.getByLabelText(label) as T;
const save = () => fireEvent.click(screen.getByRole("button", { name: "Guardar datos" }));

afterEach(() => vi.clearAllMocks());

describe("ProductDataForm", () => {
  it("muestra lo guardado, con Sin género y destacado tildado", () => {
    render(<ProductDataForm product={product} />);
    expect((screen.getByLabelText("Marca") as HTMLInputElement).value).toBe("Dior");
    expect((screen.getByLabelText("Género") as HTMLSelectElement).value).toBe("");
    expect(screen.getByRole("option", { name: "Sin género" })).toBeTruthy();
    expect((screen.getByLabelText("Destacado") as HTMLInputElement).checked).toBe(true);
  });

  it("avisa que el link no cambia aunque se corrija el nombre", () => {
    render(<ProductDataForm product={product} />);
    expect(screen.getByText("El link no cambia: /producto/dior-sauvage-edt")).toBeTruthy();
    expect(screen.getByText("La home muestra hasta 3 destacados con stock.")).toBeTruthy();
  });

  it("no tiene campo de slug: el servidor no lo lee", () => {
    const { container } = render(<ProductDataForm product={product} />);
    expect(container.querySelector('[name="slug"]')).toBeNull();
  });

  // Generated by /ship test coverage audit.
  // Value: protects=after a field error the form shows the error and keeps what the admin typed, not the saved product;
  // fails_when=the state.values branch is dropped (React resets the form and edits revert to the saved data);
  // why_new=existing tests only render the initial state; the E2E covers the success path only; seam=none;
  // no_claim=server validation itself (action mocked; parseProductData is covered in product-data.test.ts)
  // Same contract as OrderStatusForm's "decisión 48" test: the <select> must survive React's form reset.
  it("después de un error por campo lo marca y conserva lo escrito, no lo guardado (decisión 48)", async () => {
    mocks.updateProductData.mockResolvedValue({
      status: "error",
      fieldErrors: { name: NEW_PRODUCT_ERRORS.nameRequired },
      values: { brand: "Dior Paris", name: "", gender: "male", description: "Fresco y especiado" },
    } satisfies ProductDataState);
    render(<ProductDataForm product={product} />);

    // Lo que hace el admin: corrige la marca, borra el nombre, elige género, describe y destilda.
    fireEvent.change(field("Marca"), { target: { value: "Dior Paris" } });
    fireEvent.change(field("Nombre"), { target: { value: "" } });
    fireEvent.change(field<HTMLSelectElement>("Género"), { target: { value: "male" } });
    fireEvent.change(field<HTMLTextAreaElement>("Descripción"), { target: { value: "Fresco y especiado" } });
    fireEvent.click(field("Destacado"));
    save();

    await screen.findByText(NEW_PRODUCT_ERRORS.nameRequired);
    expect(field("Nombre").getAttribute("aria-invalid")).toBe("true");
    expect(field("Marca").value).toBe("Dior Paris");
    expect(field<HTMLSelectElement>("Género").value).toBe("male");
    expect(field<HTMLTextAreaElement>("Descripción").value).toBe("Fresco y especiado");
    // Lo escrito tenía Destacado sin tildar (no viaja en el form), aunque el guardado está destacado.
    expect(field("Destacado").checked).toBe(false);
    // El id del producto llega con bind, antes del estado y el FormData.
    expect(mocks.updateProductData.mock.calls[0][0]).toBe("p1");
  });

  // Generated by /ship test coverage audit.
  // Value: protects=a database failure on save is shown to the admin as an alert, with no success status;
  // fails_when=the role=alert message block is removed or gated wrongly, so a failed save looks silent;
  // why_new=no unit or E2E test renders ProductDataForm's general error; seam=none;
  // no_claim=that the action returns this message on a real DB error (covered in actions.test.ts; action mocked here)
  it("un error general (la base no guardó) se muestra como alerta, sin confirmación", async () => {
    mocks.updateProductData.mockResolvedValue({
      status: "error",
      message: PRODUCT_DATA_SAVE_ERROR,
      values: { brand: "Dior", name: "Sauvage EDT", gender: "", description: "", featured: "on" },
    } satisfies ProductDataState);
    render(<ProductDataForm product={product} />);

    save();

    expect((await screen.findByRole("alert")).textContent).toBe(PRODUCT_DATA_SAVE_ERROR);
    await waitFor(() => expect(screen.queryByRole("status")).toBeNull());
  });
});
