// @vitest-environment node
import { describe, expect, it } from "vitest";
import { getAdminProduct, getStockHistories, listAdminProducts } from "./products";
import { STOCK_HISTORY_LIMIT } from "./stock-movements";

/** Cliente falso como el de requests.test.ts: la consulta encadenada resuelve con `result`. */
function fakeClient(result: { data: unknown; error: unknown }) {
  const builder: Record<string, unknown> = {
    then: (resolve: (value: unknown) => unknown) => resolve(result),
  };
  for (const method of ["select", "eq", "order", "maybeSingle", "overrideTypes"]) {
    builder[method] = () => builder;
  }
  return { from: () => builder } as never;
}

describe("getAdminProduct", () => {
  // Generated by /ship test coverage audit.
  // Value: protects=a malformed id (22P02) is "not found" (null → notFound), but any other DB error throws instead of looking like a missing product;
  // fails_when=the branch is simplified to `if (error) return null` (an outage shows "No encontramos el producto") or the 22P02 case is dropped;
  // why_new=E2E covers only the 22P02 path through the page; no test exercises the non-22P02 error; seam=none;
  // no_claim=how the page's error boundary renders the thrown error
  it("un id mal escrito es null (no encontrado); otro error de la base se lanza, no se disfraza de no encontrado", async () => {
    const product = { id: "p1" };
    await expect(getAdminProduct(fakeClient({ data: product, error: null }), "p1")).resolves.toBe(product);
    await expect(getAdminProduct(fakeClient({ data: null, error: null }), "p1")).resolves.toBeNull();
    await expect(
      getAdminProduct(fakeClient({ data: null, error: { code: "22P02", message: "invalid input syntax for type uuid" } }), "x"),
    ).resolves.toBeNull();
    await expect(
      getAdminProduct(fakeClient({ data: null, error: { code: "57014", message: "canceling statement" } }), "p1"),
    ).rejects.toThrow("No se pudo leer el producto: canceling statement");
  });
});

describe("listAdminProducts", () => {
  // Value: protects=a DB error listing products throws (error page) instead of showing an empty list;
  // fails_when=the error branch becomes `return data ?? []` (an outage looks like "no products");
  // why_new=the E2E only covers a successful list; seam=none; no_claim=how the page renders the error
  it("devuelve las filas; un error de la base se lanza, no se muestra como lista vacía", async () => {
    const rows = [{ id: "p1" }];
    await expect(listAdminProducts(fakeClient({ data: rows, error: null }))).resolves.toBe(rows);
    await expect(
      listAdminProducts(fakeClient({ data: null, error: { code: "57014", message: "canceling statement" } })),
    ).rejects.toThrow("No se pudieron leer los productos: canceling statement");
  });
});

describe("getStockHistories", () => {
  /** Registra cada consulta: la tabla, los filtros, el orden y el límite. */
  function recordingClient(resultFor: (variantId: string) => { data: unknown; error: unknown }) {
    const calls: { table: string; eq: [string, unknown][]; order: unknown[]; limit: number | null }[] = [];
    const client = {
      from: (table: string) => {
        const call = { table, eq: [] as [string, unknown][], order: [] as unknown[], limit: null as number | null };
        calls.push(call);
        const builder: Record<string, unknown> = {
          select: () => builder,
          eq: (column: string, value: unknown) => (call.eq.push([column, value]), builder),
          order: (...args: unknown[]) => (call.order.push(args), builder),
          limit: (n: number) => ((call.limit = n), builder),
          overrideTypes: () => builder,
          then: (resolve: (value: unknown) => unknown) => resolve(resultFor(String(call.eq[0]?.[1]))),
        };
        return builder;
      },
    };
    return { client: client as never, calls };
  }

  it("trae los últimos 5 de cada presentación, del más nuevo al más viejo", async () => {
    const { client, calls } = recordingClient((id) => ({ data: [{ id: `m-${id}` }], error: null }));
    await expect(getStockHistories(client, ["v1", "v2"])).resolves.toEqual({
      v1: [{ id: "m-v1" }],
      v2: [{ id: "m-v2" }],
    });
    expect(calls).toHaveLength(2);
    for (const call of calls) {
      expect(call.table).toBe("stock_movements");
      expect(call.limit).toBe(STOCK_HISTORY_LIMIT);
      expect(call.order).toEqual([["created_at", { ascending: false }]]);
    }
    expect(calls.map((call) => call.eq)).toEqual([[["variant_id", "v1"]], [["variant_id", "v2"]]]);
  });

  it("sin presentaciones no consulta nada", async () => {
    const { client, calls } = recordingClient(() => ({ data: [], error: null }));
    await expect(getStockHistories(client, [])).resolves.toEqual({});
    expect(calls).toHaveLength(0);
  });

  it("un error de la base se lanza, no se muestra como historial vacío", async () => {
    const { client } = recordingClient(() => ({ data: null, error: { code: "57014", message: "canceling statement" } }));
    await expect(getStockHistories(client, ["v1"])).rejects.toThrow("No se pudo leer el historial de stock: canceling statement");
  });
});
